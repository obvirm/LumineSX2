pub struct ArmConstantPool {
    pub jump_targets: std::collections::HashMap<*const u8, u32>,
    pub literals: std::collections::HashMap<u128_value, u32>,
    pub base_ptr: *mut u8,
    pub capacity: u32,
    pub used: u32,
}

impl ArmConstantPool {
    pub fn new() -> Self {
        Self {
            jump_targets: std::collections::HashMap::new(),
            literals: std::collections::HashMap::new(),
            base_ptr: std::ptr::null_mut(),
            capacity: 0,
            used: 0,
        }
    }

    pub fn init(&mut self, ptr: *mut u8, capacity: u32) {
        self.base_ptr = ptr;
        self.capacity = capacity;
        self.used = 0;
        self.jump_targets.clear();
        self.literals.clear();
    }

    pub fn destroy(&mut self) {
        self.base_ptr = std::ptr::null_mut();
        self.capacity = 0;
        self.used = 0;
        self.jump_targets.clear();
        self.literals.clear();
    }

    pub fn reset(&mut self) {
        self.used = 0;
        self.jump_targets.clear();
        self.literals.clear();
    }

    fn get_remaining_capacity(&self) -> u32 {
        self.capacity - self.used
    }

    pub fn get_jump_trampoline(&mut self, target: *const u8) -> Option<*mut u8> {
        if let Some(&off) = self.jump_targets.get(&target) {
            return Some(unsafe { self.base_ptr.add(off as usize) });
        }

        let offset = align_up_pow2(self.used, 16);
        if self.capacity - offset < 20 {
            console::Console.error("Ran out of space in constant pool");
            return None;
        }

        // Emit the trampoline using a local macro-assembler.
        let mut masm = a64::MacroAssembler::new(unsafe { self.base_ptr.add(offset as usize) }, (self.capacity - offset) as usize);
        masm.mov(rx_vixl_scratch(), target as u64);
        masm.br(rx_vixl_scratch());
        masm.finalize_code();
        debug_assert!(masm.get_size_of_code_generated() < 20);

        self.jump_targets.insert(target, offset);
        self.used = offset + masm.get_size_of_code_generated() as u32;
        host_sys::flush_instruction_cache(unsafe { self.base_ptr.add(offset as usize) }, (self.used - offset) as usize);

        Some(unsafe { self.base_ptr.add(offset as usize) })
    }

    pub fn get_literal_u64(&mut self, value: u64) -> Option<*mut u8> {
        self.get_literal(u128_value::from_64(value))
    }

    pub fn get_literal(&mut self, value: u128_value) -> Option<*mut u8> {
        if let Some(&off) = self.literals.get(&value) {
            return Some(unsafe { self.base_ptr.add(off as usize) });
        }
        if self.get_remaining_capacity() < 16 {
            return None;
        }
        let offset = align_up_pow2(self.used, 16);
        unsafe {
            std::ptr::copy_nonoverlapping(
                value.as_bytes().as_ptr(),
                self.base_ptr.add(offset as usize),
                16,
            );
        }
        self.used = offset + 16;
        Some(unsafe { self.base_ptr.add(offset as usize) })
    }

    pub fn get_literal_bytes(&mut self, bytes: &[u8]) -> Option<*mut u8> {
        debug_assert!(bytes.len() <= 16, "literal length must be <= 16 bytes");
        let mut value = u128_value::default();
        let copy_len = bytes.len().min(16);
        unsafe {
            std::ptr::copy_nonoverlapping(bytes.as_ptr(), value.as_bytes().as_mut_ptr(), copy_len);
        }
        self.get_literal(value)
    }

    pub fn emit_load_literal(&self, reg: a64::CpuRegister, literal: *const u8) {
        arm_move_address_to_reg(rx_vixl_scratch(), literal);
        let asm = arm_asm().expect("no active block");
        asm.ldr(reg, a64::MemOperandKind::new(rx_vixl_scratch()));
    }
}

impl Default for ArmConstantPool {
    fn default() -> Self { Self::new() }
}

