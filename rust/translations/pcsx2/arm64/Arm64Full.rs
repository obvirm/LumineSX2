pub fn mvu_merge_regs(
    dest: a64::VectorRegister,
    src: a64::VectorRegister,
    xyzw: i32,
    mod_xyzw: bool,
    can_modify_src: bool,
) {
    let mut xyzw = xyzw & 0xF;
    if dest.get_code() != src.get_code() && xyzw != 0 {
        let asm = arm_asm().expect("no active block");
        if xyzw == 0x8 {
            asm.mov(dest.v4s(), 0u64);
            asm.dup_lane(dest.v4s(), src.v4s(), 0);
        } else if xyzw == 0xf {
            asm.mov(dest.q(), src.q());
        } else {
            if mod_xyzw {
                if xyzw == 1 {
                    asm.ins_imm(dest.v4s(), 3, src.s());
                    return;
                } else if xyzw == 2 {
                    asm.ins_imm(dest.v4s(), 2, src.s());
                    return;
                } else if xyzw == 4 {
                    asm.ins_imm(dest.v4s(), 1, src.s());
                    return;
                }
            }

            if xyzw == 0 {
                return;
            }
            if xyzw == 15 {
                asm.mov(dest.q(), src.q());
                return;
            }
            if xyzw == 14 && can_modify_src {
                asm.ins_imm(src.v4s(), 3, dest.s());
                asm.mov(dest.v16b(), src.v16b());
                return;
            }

            // reverse xyzw nibble bits: bit0<->bit3, bit1<->bit2.
            xyzw = ((xyzw & 1) << 3) | ((xyzw & 2) << 1) | ((xyzw & 4) >> 1) | ((xyzw & 8) >> 3);

            if (xyzw & 3) == 3 {
                asm.ins_imm(dest.v2d(), 0, src.s());
                xyzw &= !3;
            } else if (xyzw & 12) == 12 {
                asm.ins_imm(dest.v2d(), 1, src.s());
                xyzw &= !12;
            }

            for i in 0u32..4 {
                if (xyzw & (1 << i)) != 0 {
                    asm.ins_imm(dest.v4s(), i, src.s());
                }
            }
        }
    }
}

pub fn masked_vec_write(reg: a64::VectorRegister, addr: a64::MemOperandKind, xyzw: i32) {
    let asm = arm_asm().expect("no active block");
    match xyzw {
        5 => {
            arm_get_mem_operand_in_register(r_scratch_addr(), addr, 4);
            asm.st1(reg.v4s(), 1, a64::MemOperandKind::new(r_scratch_addr()));
            arm_get_mem_operand_in_register(r_scratch_addr(), addr, 12);
            asm.st1(reg.v4s(), 3, a64::MemOperandKind::new(r_scratch_addr()));
        }
        9 => {
            arm_get_mem_operand_in_register(r_scratch_addr(), addr, 12);
            asm.str(reg.s(), addr);
            asm.st1(reg.v4s(), 3, a64::MemOperandKind::new(r_scratch_addr()));
        }
        10 => {
            arm_get_mem_operand_in_register(r_scratch_addr(), addr, 8);
            asm.str(reg.s(), addr);
            asm.st1(reg.v4s(), 2, a64::MemOperandKind::new(r_scratch_addr()));
        }
        3 => {
            arm_get_mem_operand_in_register(r_scratch_addr(), addr, 8);
            asm.st1(reg.v2d(), 1, a64::MemOperandKind::new(r_scratch_addr()));
        }
        11 => {
            arm_get_mem_operand_in_register(r_scratch_addr(), addr, 8);
            asm.str(reg.s(), addr);
            asm.st1(reg.v2d(), 1, a64::MemOperandKind::new(r_scratch_addr()));
        }
        13 => {
            arm_get_mem_operand_in_register(r_scratch_addr(), addr, 12);
            asm.str(reg.d(), addr);
            asm.st1(reg.v4s(), 3, a64::MemOperandKind::new(r_scratch_addr()));
        }
        6 => {
            arm_get_mem_operand_in_register(r_scratch_addr(), addr, 4);
            asm.st1(reg.v4s(), 1, a64::MemOperandKind::new_offset(r_scratch_addr(), 4, a64::POST_INDEX));
            asm.st1(reg.v4s(), 2, a64::MemOperandKind::new(r_scratch_addr()));
        }
        7 => {
            arm_get_mem_operand_in_register(r_scratch_addr(), addr, 4);
            asm.st1(reg.v4s(), 1, a64::MemOperandKind::new_offset(r_scratch_addr(), 4, a64::POST_INDEX));
            asm.st1(reg.v2d(), 1, a64::MemOperandKind::new(r_scratch_addr()));
        }
        12 => asm.str(reg.d(), addr),
        14 => {
            arm_get_mem_operand_in_register(r_scratch_addr(), addr, 8);
            asm.str(reg.d(), addr);
            asm.st1(reg.v4s(), 2, a64::MemOperandKind::new(r_scratch_addr()));
        }
        4 => {
            arm_get_mem_operand_in_register(r_scratch_addr(), addr, 4);
            asm.st1(reg.v4s(), 1, a64::MemOperandKind::new(r_scratch_addr()));
        }
        2 => {
            arm_get_mem_operand_in_register(r_scratch_addr(), addr, 8);
            asm.st1(reg.v4s(), 2, a64::MemOperandKind::new(r_scratch_addr()));
        }
        1 => {
            arm_get_mem_operand_in_register(r_scratch_addr(), addr, 12);
            asm.st1(reg.v4s(), 3, a64::MemOperandKind::new(r_scratch_addr()));
        }
        8 => asm.str(reg.s(), addr),
        0 => console::Console.error("maskedVecWrite case 0!"),
        _ => asm.str(reg.q(), addr),
    }
}

