pub fn arm_set_asm_ptr(ptr: *mut u8, capacity: usize, pool: Option<&mut ArmConstantPool>) {
    with_ctx(|c| {
        debug_assert!(c.asm.is_none(), "arm_asm already set on this thread");
        c.asm_ptr = ptr;
        c.asm_capacity = capacity;
        c.constant_pool = pool.map(|p| p as *mut _);
    });
}

pub fn arm_align_asm_ptr() {
    with_ctx(|c| {
        const ALIGNMENT: usize = 16;
        let cur = c.asm_ptr as usize;
        let new = (cur + ALIGNMENT - 1) & !(ALIGNMENT - 1);
        let pad = new - cur;
        c.asm_capacity = c.asm_capacity.saturating_sub(pad);
        c.asm_ptr = new as *mut u8;
    });
}

pub fn arm_has_block() -> bool {
    with_ctx(|c| c.asm.is_some())
}

pub fn arm_get_current_code_pointer() -> *mut u8 {
    with_ctx(|c| unsafe {
        let off = c.asm.as_ref().map(|a| a.get_cursor_offset()).unwrap_or(0);
        c.asm_ptr.add(off)
    })
}

pub fn arm_get_asm_ptr() -> *mut u8 { with_ctx(|c| c.asm_ptr) }

pub fn arm_start_block() -> *mut u8 {
    arm_align_asm_ptr();
    host_sys::begin_code_write();
    let ptr = with_ctx(|c| {
        debug_assert!(c.asm.is_none());
        c.asm = Some(a64::MacroAssembler::new(c.asm_ptr, c.asm_capacity));
        c.asm_ptr
    });
    // Mirror the C++ behavior: reserve scratch register 31 / 17.
    if let Some(asm) = arm_asm() {
        let _ = asm; // would call GetScratchVRegisterList()->Remove(31) here
    }
    ptr
}

pub fn arm_end_block() -> *mut u8 {
    let (ptr, size) = with_ctx(|c| {
        let size = c.asm.as_ref().map(|a| a.get_size_of_code_generated()).unwrap_or(0);
        if let Some(mut asm) = c.asm.take() {
            asm.finalize_code();
        }
        let new_ptr = unsafe { c.asm_ptr.add(size) };
        c.asm_capacity = c.asm_capacity.saturating_sub(size);
        c.asm_ptr = new_ptr;
        (new_ptr, size)
    });
    host_sys::end_code_write();
    host_sys::flush_instruction_cache(ptr, size);
    ptr
}

