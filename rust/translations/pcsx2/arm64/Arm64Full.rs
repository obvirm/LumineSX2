// ---------------------------------------------------------------------------
// Thread-local state for the dynarec context.
// ---------------------------------------------------------------------------

use std::cell::UnsafeCell;
use std::sync::Once;

thread_local! {
    static ARM_CTX: UnsafeCell<ArmContext> = UnsafeCell::new(ArmContext::new());
}

struct ArmContext {
    asm: Option<a64::MacroAssembler>,
    asm_ptr: *mut u8,
    asm_capacity: usize,
    constant_pool: Option<*mut ArmConstantPool>,
}

impl ArmContext {
    const fn new() -> Self {
        Self {
            asm: None,
            asm_ptr: std::ptr::null_mut(),
            asm_capacity: 0,
            constant_pool: None,
        }
    }
}

unsafe impl Send for ArmContext {}
unsafe impl Sync for ArmContext {}

fn with_ctx<F, R>(f: F) -> R
where
    F: FnOnce(&mut ArmContext) -> R,
{
    ARM_CTX.with(|c| {
        let ctx = c.get();
        // SAFETY: this is a thread_local cell, only this thread accesses it.
        f(unsafe { &mut *ctx })
    })
}

// Convenience accessors matching the C++ globals.
pub fn arm_asm() -> Option<&'static mut a64::MacroAssembler> {
    with_ctx(|c| c.asm.as_mut().map(|a| {
        // SAFETY: caller must ensure no aliasing across the asm reference.
        unsafe { &mut *(a as *mut a64::MacroAssembler) }
    }))
}

pub fn arm_asm_ptr() -> *mut u8 { with_ctx(|c| c.asm_ptr) }
pub fn arm_asm_capacity() -> usize { with_ctx(|c| c.asm_capacity) }
pub fn arm_constant_pool() -> Option<&'static mut ArmConstantPool> {
    with_ctx(|c| c.constant_pool.and_then(|p| if p.is_null() { None } else { Some(unsafe { &mut *p }) }))
}

