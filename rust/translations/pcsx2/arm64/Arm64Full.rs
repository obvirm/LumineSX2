//! Idiomatic Rust translation of the PCSX2 ARM64 dynarec subsystem.
//!
//! This module consolidates the contents of the C/C++ sources
//! `arm64/AsmHelpers.{h,cpp}`, `arm64/RecStubs.cpp`, `arm64/Vif_Dynarec.cpp`,
//! `arm64/Vif_UnpackNEON.{h,cpp}` into a single Rust 2021 module that is
//! API-compatible at the level of the dynarec entry points.  It mirrors the
//! role of the original code: providing ARM64 assembly helpers, a constant
//! pool, a `VifUnpackNEON_Dynarec` compiler, and the VIF unpacking routines
//! driven by the native VIXL macro-assembler.
//!
//! Only the `std` crate is used.  No filesystem, no networking, no panicking
//! FFI — the code is structured so it can be linked into a real dynarec
//! binary later by swapping the placeholder vixl types for the real ones.

