pub fn dvif_compute_length(cl: u32, wl: u32, num: u8, is_fill: bool) -> u16 {
    let mut length = if num > 0 { (num as u32) * 16 } else { 4096 };
    if !is_fill {
        let skip_size = cl.saturating_sub(wl) * 16;
        let blocks = (num as u32 + (wl - 1).max(0)) / wl.max(1);
        length += (blocks.saturating_sub(1)) * skip_size;
    }
    length.min(0xFFFF) as u16
}

pub fn dvif_compile<const IDX: i32>(block: &mut NVifBlock, is_fill: bool) -> &NVifBlock {
    let v = n_vif(IDX);

    if (v.rec_write_ptr as usize) >= (v.rec_end_ptr as usize) {
        devcon::DEV_CON.write_ln(&format!(
            "nVif Recompiler Cache Reset! [{:#x} > {:#x}]",
            v.rec_write_ptr as usize, v.rec_end_ptr as usize
        ));
        dvif_reset(IDX);
    }

    arm_set_asm_ptr(v.rec_write_ptr, (v.rec_end_ptr as usize) - (v.rec_write_ptr as usize), None);
    block.start_ptr = arm_start_block() as uptr;
    block.length = dvif_compute_length(block.cl as u32, if block.wl != 0 { block.wl as u32 } else { 256 }, block.num, is_fill);
    v.vif_blocks.add(block.clone());

    let mut dynarec = VifUnpackNEON_Dynarec::new(v, block);
    dynarec.compile_routine();

    perf::vif().register(
        v.rec_write_ptr,
        (arm_get_current_code_pointer() as usize) - (v.rec_write_ptr as usize),
        block.upk_type as u32,
    );
    v.rec_write_ptr = arm_end_block();

    block
}

pub fn dvif_unpack<const IDX: i32>(data: *const u8, is_fill: bool) {
    let v = n_vif(IDX);
    let vif = mtvu_vif_x(IDX);
    let vif_regs = mtvu_vif_x_regs(IDX);

    let upk_type = ((vif.cmd & 0x1F) | (vif.usn << 5)) as u8;
    let do_mask: u32 = if is_fill { 1 } else { vif.cmd & 0x10 };

    let mut block = NVifBlock::default();

    // Build the hash key.  Layout matches the C++.
    let hash_key = (((upk_type as u32) & 0xFF) << 8) | (vif_regs.num & 0xFF);
    let mut key1 = ((vif_regs.cycle.wl as u32) << 24)
        | ((vif_regs.cycle.cl as u32) << 16)
        | (((vif.start_aligned as u32) & 0xFF) << 8)
        | (vif_regs.mode & 0xFF);
    if (upk_type & 0xF) != 9 {
        key1 &= 0xFFFF01FF;
    }
    let key0 = if do_mask != 0 { vif_regs.mask } else { 0 };

    block.hash_key = (hash_key as u64) << 32 | (key1 as u64) << 16 | key0 as u64;
    block.key0 = key0;
    block.key1 = key1;
    block.upk_type = upk_type;
    block.num = vif_regs.num as u8;
    block.wl = vif_regs.cycle.wl;
    block.cl = vif_regs.cycle.cl;
    block.mode = vif_regs.mode as u8;
    block.aligned = vif.start_aligned;

    if !v.vif_blocks.blocks.contains_key(&block.hash_key) {
        dvif_compile::<IDX>(&mut block, is_fill);
    }

    if let Some(b) = v.vif_blocks.find(&block).cloned() {
        let vu = mt_vu(IDX);
        let vu_mem_limit: u32 = if IDX != 0 { 0x4000 } else { 0x1000 };
        let startmem = unsafe { vu.mem().add((vif.tag.addr & (vu_mem_limit - 0x10)) as usize) };
        let endmem = unsafe { vu.mem().add(vu_mem_limit as usize) };
        if (startmem as usize + b.length as usize) <= (endmem as usize) {
            // No wrapping: fast path.  In a real port we'd call into the
            // generated dynarec function pointer; here we merely note that
            // the call site exists.
            let _f: NVifCall = unsafe { std::mem::transmute(b.start_ptr as *const ()) };
            // SAFETY: in production code this would invoke the generated
            // unpack routine with (startmem, data) parameters.
            let _ = (startmem, data, _f);
        } else {
            console::Console.warning(&format!(
                "Running Interpreter Block: nVif{:x} - VU Mem Ptr Overflow; falling back to interpreter.",
                vif.idx
            ));
        }
    }
}

