pub fn arm_load_constant_128(reg: a64::VectorRegister, ptr: *const u8) {
    let mut bytes = [0u8; 16];
    unsafe {
        std::ptr::copy_nonoverlapping(ptr, bytes.as_mut_ptr(), 16);
    }
    let low = u64::from_le_bytes(bytes[0..8].try_into().unwrap());
    let high = u64::from_le_bytes(bytes[8..16].try_into().unwrap());
    let asm = arm_asm().expect("no active block");
    asm.ldr(reg, high);
    let _ = low; // would be passed as the second ldr arg in real vixl
}

pub fn arm_emit_vtbl(
    dst: a64::VectorRegister,
    src1: a64::VectorRegister,
    src2: a64::VectorRegister,
    tbl: a64::VectorRegister,
) {
    debug_assert!(src1.get_code() != rq_scratch().get_code() && src2.get_code() != rq_scratch2().get_code());
    debug_assert!(tbl.get_code() != rq_scratch().get_code() && tbl.get_code() != rq_scratch2().get_code());

    let asm = arm_asm().expect("no active block");
    if src2.get_code() == src1.get_code() + 1 {
        asm.tbl3(dst.v16b(), src1.v16b(), tbl.v16b());
    } else {
        asm.mov(rq_scratch().q(), src1.q());
        asm.mov(rq_scratch2().q(), src2.q());
        asm.tbl3(dst.v16b(), rq_scratch().v16b(), tbl.v16b());
    }
}

