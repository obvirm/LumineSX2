pub fn dvif_reset(idx: i32) {
    let v = n_vif(idx);
    v.vif_blocks.reset();
    let offset = if idx != 0 { host_memory_map::VIF1_REC_OFFSET } else { host_memory_map::VIF0_REC_OFFSET };
    let size = if idx != 0 { host_memory_map::VIF1_REC_SIZE } else { host_memory_map::VIF0_REC_SIZE };
    v.rec_write_ptr = sys_memory::get_code_ptr(offset);
    unsafe {
        v.rec_end_ptr = v.rec_write_ptr.add(size - _256KB);
    }
}

pub fn dvif_release(idx: i32) {
    n_vif(idx).vif_blocks.clear();
}

