impl VifUnpackNEON_Dynarec {
    pub fn new(v: &NVifStruct, v_block: &NVifBlock) -> Self {
        let wl = if v_block.wl != 0 { v_block.wl as i32 } else { 256 };
        let is_fill = (v_block.cl as i32) < wl;
        let usn = ((v_block.upk_type >> 5) & 1) != 0;
        let do_mask = ((v_block.upk_type >> 4) & 1) != 0;
        let do_mode = v_block.mode & 3;
        let is_aligned = v_block.aligned as i32;
        Self {
            v_idx: v.idx,
            v_block: v_block.clone(),
            is_fill,
            usn,
            do_mask,
            do_mode,
            is_aligned,
            vcl: 0,
            unpk_loop_iteration: 0,
            unpk_no_of_iterations: 0,
            skip_processing: false,
            input_masked: false,
            dst_indirect: a64::MemOperandKind::new(rx_arg1()),
            src_indirect: a64::MemOperandKind::new(rx_arg2()),
            work_reg: a64::Q1,
            dest_reg: a64::Q0,
            work_gpr_w: a64::W4,
            xmm_col0: a64::Q2,
            xmm_col1: a64::Q3,
            xmm_col2: a64::Q4,
            xmm_col3: a64::Q5,
            xmm_row: a64::Q6,
            xmm_temp: a64::Q7,
        }
    }

    pub fn is_write_protected_op(&self) -> bool { self.skip_processing }
    pub fn is_input_masked(&self) -> bool { self.input_masked }
    pub fn is_unmasked_op(&self) -> bool { !self.do_mask && self.do_mode == 0 }

    pub fn set_masks(&self, c_s: i32) {
        let vif = mtvu_vif_x(self.v_idx);
        let m0 = self.v_block.mask;
        let m3 = ((m0 & 0xAAAAAAAA) >> 1) & !m0;
        let m2 = (m0 & 0x55555555) & (!m0 >> 1);

        if (self.do_mask && m2 != 0) || self.do_mode != 0 {
            arm_load_ptr(a64::CpuRegister::from_vec(self.xmm_row), &vif.mask_row as *const _ as *const u8);
        }
        if self.do_mask && m3 != 0 {
            arm_load_ptr(a64::CpuRegister::from_vec(self.xmm_col0), &vif.mask_col as *const _ as *const u8);
            let asm = arm_asm().expect("no active block");
            if c_s >= 2 && (m3 & 0x0000FF00) != 0 {
                asm.dup_lane(self.xmm_col1.v4s(), self.xmm_col0.v4s(), 1);
            }
            if c_s >= 3 && (m3 & 0x00FF0000) != 0 {
                asm.dup_lane(self.xmm_col2.v4s(), self.xmm_col0.v4s(), 2);
            }
            if c_s >= 4 && (m3 & 0xFF000000) != 0 {
                asm.dup_lane(self.xmm_col3.v4s(), self.xmm_col0.v4s(), 3);
            }
            if c_s >= 1 && (m3 & 0x000000FF) != 0 {
                asm.dup_lane(self.xmm_col0.v4s(), self.xmm_col0.v4s(), 0);
            }
        }
    }

    pub fn do_mask_write(&self, reg_x: a64::VectorRegister) {
        px_assert_msg(reg_x.get_code() <= 1, "Reg Overflow! XMM2 thru XMM6 are reserved for masking.");

        let cc = std::cmp::min(self.vcl, 3) as u32;
        let m0 = (self.v_block.mask >> (cc * 8)) & 0xFF;
        let m3 = ((m0 & 0xAA) >> 1) & !m0;
        let m2 = (m0 & 0x55) & (!m0 >> 1);
        let m4 = (m0 & !((m3 << 1) | m2)) & 0x55;

        let mut m2 = m2 as u32;
        let mut m3 = m3 as u32;
        let mut m4 = m4 as u32;
        make_merge_mask(&mut m2);
        make_merge_mask(&mut m3);
        make_merge_mask(&mut m4);

        if self.do_mask && m2 != 0 {
            mvu_merge_regs(reg_x, self.xmm_row, m2 as i32, false, false);
        }
        if self.do_mask && m3 != 0 {
            mvu_merge_regs(reg_x, arm_q_register(self.xmm_col0.get_code() as i32 + cc as i32), m3 as i32, false, false);
        }
        if self.do_mode != 0 {
            let mut m5 = !(m2 | m3 | m4) & 0xF;
            if !self.do_mask {
                m5 = 0xF;
            }
            if m5 < 0xF {
                let asm = arm_asm().expect("no active block");
                asm.movi(self.xmm_temp.v4s(), 0);
                if self.do_mode == 3 {
                    mvu_merge_regs(self.xmm_row, reg_x, m5 as i32, false, false);
                } else {
                    mvu_merge_regs(self.xmm_temp, self.xmm_row, m5 as i32, false, false);
                    asm.add(reg_x.v4s(), reg_x.v4s(), self.xmm_temp.v4s());
                    if self.do_mode == 2 {
                        mvu_merge_regs(self.xmm_row, reg_x, m5 as i32, false, false);
                    }
                }
            } else {
                let asm = arm_asm().expect("no active block");
                if self.do_mode == 3 {
                    asm.mov(self.xmm_row.q(), reg_x.q());
                } else {
                    asm.add(reg_x.v4s(), reg_x.v4s(), self.xmm_row.v4s());
                    if self.do_mode == 2 {
                        asm.mov(self.xmm_row.q(), reg_x.q());
                    }
                }
            }
        }
        if self.do_mask && m4 != 0 {
            masked_vec_write(reg_x, self.dst_indirect, (m4 ^ 0xF) as i32);
        } else {
            let asm = arm_asm().expect("no active block");
            asm.str(reg_x.q(), self.dst_indirect);
        }
    }

    pub fn write_back_row(&self) {
        let vif = mtvu_vif_x(self.v_idx);
        arm_store_ptr(a64::CpuRegister::from_vec(self.xmm_row), &vif.mask_row as *const _ as *const u8);
    }

    pub fn mod_unpack(&mut self, upk_num: i32, post_op: bool) {
        match upk_num {
            0 | 1 | 2 => {
                if post_op {
                    self.unpk_loop_iteration += 1;
                    self.unpk_loop_iteration &= 0x3;
                }
            }
            4 | 5 | 6 => {
                if post_op {
                    self.unpk_loop_iteration += 1;
                    self.unpk_loop_iteration &= 0x1;
                }
            }
            8 => {
                if post_op {
                    self.unpk_loop_iteration += 1;
                    self.unpk_loop_iteration &= 0x1;
                }
            }
            9 | 10 => {
                if !post_op {
                    self.unpk_loop_iteration += 1;
                }
            }
            12 | 13 | 14 | 15 => {}
            3 | 7 | 11 => {
                console::Console.warning(&format!("Vpu/Vif: Invalid Unpack {}", upk_num));
            }
            _ => {}
        }
    }

    pub fn process_masks(&mut self) {
        self.skip_processing = false;
        self.input_masked = false;
        if !self.do_mask {
            return;
        }
        let cc = std::cmp::min(self.vcl, 3) as u32;
        let full_mask = (self.v_block.mask >> (cc * 8)) & 0xFF;
        let rowcol_mask = ((full_mask >> 1) | full_mask) & 0x55;

        self.skip_processing = full_mask == 0xFF;
        self.input_masked = rowcol_mask == 0x55;
    }

    pub fn x_mov_dest(&self) {
        if self.is_write_protected_op() {
            return;
        }
        if self.is_unmasked_op() {
            let asm = arm_asm().expect("no active block");
            asm.str(self.dest_reg.q(), self.dst_indirect);
        } else {
            self.do_mask_write(self.dest_reg);
        }
    }

    pub fn compile_routine(&mut self) {
        let wl = if self.v_block.wl != 0 { self.v_block.wl as i32 } else { 256 };
        let upk_num = (self.v_block.upk_type & 0xF) as i32;
        let vift = NVIFT[upk_num as usize];
        let cycle_size = if self.is_fill { self.v_block.cl as i32 } else { wl };
        let block_size = if self.is_fill { wl } else { self.v_block.cl as i32 };
        let skip_size = block_size - cycle_size;

        let mut v_num = if self.v_block.num != 0 { self.v_block.num as u32 } else { 256 };
        if upk_num == 0xF {
            self.do_mode = 0;
        }
        self.unpk_no_of_iterations = 0;
        debug_assert_eq!(self.vcl, 0);

        // Decide the # of column registers to load.
        self.set_masks(if self.is_fill { block_size } else { cycle_size });

        while v_num > 0 {
            self.process_masks();

            if self.vcl < cycle_size {
                self.mod_unpack(upk_num, false);
                self.x_unpack(upk_num);
                self.x_mov_dest();
                self.mod_unpack(upk_num, true);

                self.dst_indirect = arm_offset_mem_operand(self.dst_indirect, 16);
                self.src_indirect = arm_offset_mem_operand(self.src_indirect, vift as i64);

                v_num -= 1;
                self.vcl += 1;
                if self.vcl == block_size {
                    self.vcl = 0;
                }
            } else if self.is_fill {
                self.x_unpack(upk_num);
                self.x_mov_dest();
                self.dst_indirect = arm_offset_mem_operand(self.dst_indirect, 16);
                v_num -= 1;
                self.vcl += 1;
                if self.vcl == block_size {
                    self.vcl = 0;
                }
            } else {
                self.dst_indirect = arm_offset_mem_operand(self.dst_indirect, 16 * skip_size as i64);
                self.vcl = 0;
            }
        }

        if self.do_mode >= 2 {
            self.write_back_row();
        }
        let asm = arm_asm().expect("no active block");
        asm.ret();
    }

    // ----- Unpacker primitives --------------------------------------------

    fn x_shift_r(&self, reg_x: a64::VectorRegister, n: u32) {
        let asm = arm_asm().expect("no active block");
        if self.usn {
            asm.ushr(reg_x.v4s(), reg_x.v4s(), n);
        } else {
            asm.sshr(reg_x.v4s(), reg_x.v4s(), n);
        }
    }

    fn x_pmovxx8(&self, reg_x: a64::VectorRegister) {
        let asm = arm_asm().expect("no active block");
        asm.ldr(reg_x.s(), self.src_indirect);
        if self.usn {
            asm.ushll(reg_x.v8h(), reg_x.v8b(), 0);
            asm.ushll(reg_x.v4s(), reg_x.v4h(), 0);
        } else {
            asm.sshll(reg_x.v8h(), reg_x.v8b(), 0);
            asm.sshll(reg_x.v4s(), reg_x.v4h(), 0);
        }
    }

    fn x_pmovxx16(&self, reg_x: a64::VectorRegister) {
        let asm = arm_asm().expect("no active block");
        asm.ldr(reg_x.d(), self.src_indirect);
        if self.usn {
            asm.ushll(reg_x.v4s(), reg_x.v4h(), 0);
        } else {
            asm.sshll(reg_x.v4s(), reg_x.v4h(), 0);
        }
    }

    fn x_unpack(&self, upk_num: i32) {
        match upk_num {
            0 => self.x_upk_s_32(),
            1 => self.x_upk_s_16(),
            2 => self.x_upk_s_8(),
            4 => self.x_upk_v2_32(),
            5 => self.x_upk_v2_16(),
            6 => self.x_upk_v2_8(),
            8 => self.x_upk_v3_32(),
            9 => self.x_upk_v3_16(),
            10 => self.x_upk_v3_8(),
            12 => self.x_upk_v4_32(),
            13 => self.x_upk_v4_16(),
            14 => self.x_upk_v4_8(),
            15 => self.x_upk_v4_5(),
            3 | 7 | 11 => {
                console::Console.warning(&format!("Vpu/Vif: Invalid Unpack {}", upk_num));
            }
            _ => {}
        }
    }

    fn x_upk_s_32(&self) {
        let asm = arm_asm().expect("no active block");
        if self.unpk_loop_iteration == 0 {
            asm.ldr(self.work_reg.q(), self.src_indirect);
        }
        if self.is_input_masked() { return; }
        match self.unpk_loop_iteration {
            0 => asm.dup_lane(self.dest_reg.v4s(), self.work_reg.v4s(), 0),
            1 => asm.dup_lane(self.dest_reg.v4s(), self.work_reg.v4s(), 1),
            2 => asm.dup_lane(self.dest_reg.v4s(), self.work_reg.v4s(), 2),
            3 => asm.dup_lane(self.dest_reg.v4s(), self.work_reg.v4s(), 3),
            _ => {}
        }
    }

    fn x_upk_s_16(&self) {
        let asm = arm_asm().expect("no active block");
        if self.unpk_loop_iteration == 0 {
            self.x_pmovxx16(self.work_reg);
        }
        if self.is_input_masked() { return; }
        match self.unpk_loop_iteration {
            0 => asm.dup_lane(self.dest_reg.v4s(), self.work_reg.v4s(), 0),
            1 => asm.dup_lane(self.dest_reg.v4s(), self.work_reg.v4s(), 1),
            2 => asm.dup_lane(self.dest_reg.v4s(), self.work_reg.v4s(), 2),
            3 => asm.dup_lane(self.dest_reg.v4s(), self.work_reg.v4s(), 3),
            _ => {}
        }
    }

    fn x_upk_s_8(&self) {
        let asm = arm_asm().expect("no active block");
        if self.unpk_loop_iteration == 0 {
            self.x_pmovxx8(self.work_reg);
        }
        if self.is_input_masked() { return; }
        match self.unpk_loop_iteration {
            0 => asm.dup_lane(self.dest_reg.v4s(), self.work_reg.v4s(), 0),
            1 => asm.dup_lane(self.dest_reg.v4s(), self.work_reg.v4s(), 1),
            2 => asm.dup_lane(self.dest_reg.v4s(), self.work_reg.v4s(), 2),
            3 => asm.dup_lane(self.dest_reg.v4s(), self.work_reg.v4s(), 3),
            _ => {}
        }
    }

    fn x_upk_v2_32(&self) {
        let asm = arm_asm().expect("no active block");
        if self.unpk_loop_iteration == 0 {
            asm.ldr(self.work_reg.q(), self.src_indirect);
            if self.is_input_masked() { return; }
            asm.dup_lane(self.dest_reg.v2d(), self.work_reg.v2d(), 0);
            if self.is_aligned != 0 {
                asm.ins_imm(self.dest_reg.v4s(), 3, a64::wzr);
            }
        } else {
            if self.is_input_masked() { return; }
            asm.dup_lane(self.dest_reg.v2d(), self.work_reg.v2d(), 1);
            if self.is_aligned != 0 {
                asm.ins_imm(self.dest_reg.v4s(), 3, a64::wzr);
            }
        }
    }

    fn x_upk_v2_16(&self) {
        let asm = arm_asm().expect("no active block");
        if self.unpk_loop_iteration == 0 {
            self.x_pmovxx16(self.work_reg);
            if self.is_input_masked() { return; }
            asm.dup_lane(self.dest_reg.v2d(), self.work_reg.v2d(), 0);
        } else {
            if self.is_input_masked() { return; }
            asm.dup_lane(self.dest_reg.v2d(), self.work_reg.v2d(), 1);
        }
    }

    fn x_upk_v2_8(&self) {
        let asm = arm_asm().expect("no active block");
        if self.unpk_loop_iteration == 0 {
            self.x_pmovxx8(self.work_reg);
            if self.is_input_masked() { return; }
            asm.dup_lane(self.dest_reg.v2d(), self.work_reg.v2d(), 0);
        } else {
            if self.is_input_masked() { return; }
            asm.dup_lane(self.dest_reg.v2d(), self.work_reg.v2d(), 1);
        }
    }

    fn x_upk_v3_32(&self) {
        if self.is_input_masked() { return; }
        let asm = arm_asm().expect("no active block");
        asm.ldr(self.dest_reg.q(), self.src_indirect);
        if self.unpk_loop_iteration != self.is_aligned {
            asm.ins_imm(self.dest_reg.v4s(), 3, a64::wzr);
        }
    }

    fn x_upk_v3_16(&self) {
        if self.is_input_masked() { return; }
        self.x_pmovxx16(self.dest_reg);
        let result = (((self.unpk_loop_iteration / 4) + 1 + (4 - self.is_aligned)) & 0x3) as i32;
        let asm = arm_asm().expect("no active block");
        if (self.unpk_loop_iteration & 1) == 0 && result == 0 {
            asm.ins_imm(self.dest_reg.v4s(), 3, a64::wzr);
        }
    }

    fn x_upk_v3_8(&self) {
        if self.is_input_masked() { return; }
        self.x_pmovxx8(self.dest_reg);
        let asm = arm_asm().expect("no active block");
        if self.unpk_loop_iteration != self.is_aligned {
            asm.ins_imm(self.dest_reg.v4s(), 3, a64::wzr);
        }
    }

    fn x_upk_v4_32(&self) {
        if self.is_input_masked() { return; }
        let asm = arm_asm().expect("no active block");
        asm.ldr(self.dest_reg.q(), self.src_indirect);
    }

    fn x_upk_v4_16(&self) {
        if self.is_input_masked() { return; }
        self.x_pmovxx16(self.dest_reg);
    }

    fn x_upk_v4_8(&self) {
        if self.is_input_masked() { return; }
        self.x_pmovxx8(self.dest_reg);
    }

    fn x_upk_v4_5(&self) {
        if self.is_input_masked() { return; }
        let asm = arm_asm().expect("no active block");
        asm.ldrh(self.work_gpr_w, self.src_indirect);
        asm.lsl(self.work_gpr_w, self.work_gpr_w, 3);
        asm.dup(self.work_gpr_w.x(), self.work_gpr_w);
        asm.lsr(self.work_gpr_w, self.work_gpr_w, 8);
        asm.lsl(self.work_gpr_w, self.work_gpr_w, 3);
        asm.ins_imm(self.dest_reg.v4s(), 1, self.work_gpr_w);
        asm.lsr(self.work_gpr_w, self.work_gpr_w, 8);
        asm.lsl(self.work_gpr_w, self.work_gpr_w, 3);
        asm.ins_imm(self.dest_reg.v4s(), 2, self.work_gpr_w);
        asm.lsr(self.work_gpr_w, self.work_gpr_w, 8);
        asm.lsl(self.work_gpr_w, self.work_gpr_w, 7);
        asm.ins_imm(self.dest_reg.v4s(), 3, self.work_gpr_w);
        asm.shl(self.dest_reg.v4s(), self.dest_reg.v4s(), 24);
        asm.ushr(self.dest_reg.v4s(), self.dest_reg.v4s(), 24);
    }
}

pub fn make_merge_mask(x: &mut u32) {
    *x = ((*x & 0x40) >> 6) | ((*x & 0x10) >> 3) | (*x & 4) | ((*x & 1) << 3);
}

